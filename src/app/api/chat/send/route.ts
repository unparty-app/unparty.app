import { NextResponse } from 'next/server';
import { checkRateLimit, getClientIp } from '@/lib/rate-limit';
import { auth } from '@/lib/auth-stub.server';
import { prisma } from '@/lib/prisma';

const SLACK_WEBHOOK_URL = process.env.SLACK_WEBHOOK_URL_CHAT;

// Field size caps — keep Slack payloads sane and reject junk submissions
const MAX_MESSAGE_LENGTH = 2000;
const MAX_EMAIL_LENGTH = 254;
const MAX_FIRST_NAME_LENGTH = 100;
const MAX_CONTEXT_LENGTH = 200;

// Per-IP limits (anonymous senders): short window blocks bursts, long window
// blocks slow drips
const RATE_LIMIT_PER_MINUTE = 3;
const RATE_LIMIT_PER_HOUR = 10;

// Per-user limits (signed-in senders): looser than the IP limits since a
// signed-in user is identifiable/accountable rather than an anonymous shared IP
const RATE_LIMIT_PER_MINUTE_AUTH = 5;
const RATE_LIMIT_PER_HOUR_AUTH = 20;

// Type definitions for request and Slack API
interface ChatRequest {
  message: string;
  email: string;
  firstName: string;
  context?: string;
  // Honeypot — rendered invisibly in the form; humans leave it empty
  website?: string;
  // Human-verification math challenge generated by the form
  challenge?: { a: number; b: number; answer: number };
}

// The challenge is verified for internal consistency (answer must equal
// a + b for small positive integers), which stops naive form-fillers and
// direct API replays that don't compute the sum.
function isValidChallenge(challenge: ChatRequest['challenge']): boolean {
  if (!challenge || typeof challenge !== 'object') return false;
  const { a, b, answer } = challenge;
  if (![a, b, answer].every((n) => typeof n === 'number' && Number.isInteger(n))) return false;
  if (a < 1 || a > 20 || b < 1 || b > 20) return false;
  return a + b === answer;
}

interface SlackBlock {
  type: string;
  text?: {
    type: string;
    text: string;
    emoji?: boolean;
  };
  fields?: Array<{
    type: string;
    text: string;
  }>;
}

interface SlackPayload {
  text: string;
  blocks: SlackBlock[];
}

interface SlackApiResponse {
  ok: boolean;
  error?: string;
}

export async function POST(req: Request) {
  try {
    // Signed-in senders are rate-limited by user id (looser ceiling, since
    // they're identifiable) instead of by IP; anonymous senders keep the
    // stricter IP-based limits.
    const { userId } = await auth();

    const minuteLimit = userId
      ? checkRateLimit(`chat:1m:user:${userId}`, RATE_LIMIT_PER_MINUTE_AUTH, 60_000)
      : checkRateLimit(`chat:1m:${getClientIp(req)}`, RATE_LIMIT_PER_MINUTE, 60_000);
    const hourLimit = userId
      ? checkRateLimit(`chat:1h:user:${userId}`, RATE_LIMIT_PER_HOUR_AUTH, 3_600_000)
      : checkRateLimit(`chat:1h:${getClientIp(req)}`, RATE_LIMIT_PER_HOUR, 3_600_000);
    if (!minuteLimit.allowed || !hourLimit.allowed) {
      const retryAfter = Math.max(minuteLimit.retryAfterSeconds, hourLimit.retryAfterSeconds);
      return NextResponse.json(
        { message: 'Too many messages. Please wait a bit and try again.' },
        { status: 429, headers: { 'Retry-After': String(retryAfter) } }
      );
    }

    // Validate request body
    const body = await req.json();
    const { message, email, firstName, context, website, challenge } = body as ChatRequest;

    // Honeypot tripped — a bot filled the invisible field. Pretend success
    // (so the bot doesn't adapt) but never forward to Slack.
    if (typeof website === 'string' && website.trim() !== '') {
      console.warn('Chat honeypot tripped, dropping message');
      return NextResponse.json(
        { message: 'Message sent to Slack successfully' },
        { status: 200 }
      );
    }

    // Validate required fields
    if (!message || !email || !firstName) {
      return NextResponse.json(
        { message: 'Message, email, and firstName are required' },
        { status: 400 }
      );
    }

    // Enforce field size caps
    if (
      message.length > MAX_MESSAGE_LENGTH ||
      email.length > MAX_EMAIL_LENGTH ||
      firstName.length > MAX_FIRST_NAME_LENGTH ||
      (typeof context === 'string' && context.length > MAX_CONTEXT_LENGTH)
    ) {
      return NextResponse.json(
        { message: 'One or more fields exceed the allowed length' },
        { status: 400 }
      );
    }

    // Verify the human-verification challenge — skipped for signed-in senders,
    // whose Clerk session already establishes they're not a bot
    if (!userId && !isValidChallenge(challenge)) {
      return NextResponse.json(
        { message: 'Human verification failed. Please answer the verification question.' },
        { status: 400 }
      );
    }

    // Validate email format
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      return NextResponse.json(
        { message: 'Invalid email format' },
        { status: 400 }
      );
    }

    // Sanitize inputs
    const sanitizeText = (text: string): string => {
      return text
        .replace(/[<>]/g, '')
        .replace(/&/g, '&amp;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#x27;')
        .replace(/\//g, '&#x2F;');
    };

    const sanitizedMessage = sanitizeText(message);
    const sanitizedEmail = sanitizeText(email);
    const sanitizedFirstName = sanitizeText(firstName);
    const sanitizedContext = context ? sanitizeText(context) : undefined;

    // Format message for Slack with email context
    const formattedMessage = `
*New Message from Website*
*From:* ${sanitizedFirstName} (${sanitizedEmail})
${sanitizedContext ? `*Context:* ${sanitizedContext}\n` : ''}*Message:*
${sanitizedMessage}
`;

    const payload: SlackPayload = {
      text: formattedMessage,
      blocks: [
        {
          type: "header",
          text: {
            type: "plain_text",
            text: "New Message from Website",
            emoji: true
          }
        },
        {
          type: "section",
          fields: [
            {
              type: "mrkdwn",
              text: `*From:*\n${sanitizedFirstName} (${sanitizedEmail})`
            },
            ...(sanitizedContext
              ? [{ type: "mrkdwn", text: `*Context:*\n${sanitizedContext}` }]
              : [])
          ]
        },
        {
          type: "section",
          text: {
            type: "mrkdwn",
            text: `*Message:*\n${sanitizedMessage}`
          }
        }
      ]
    };

    // Validate Slack webhook URL exists
    if (!SLACK_WEBHOOK_URL) {
      console.error('Slack webhook URL is not configured');
      return NextResponse.json(
        { message: 'Internal server error' },
        { status: 500 }
      );
    }

    const response = await fetch(SLACK_WEBHOOK_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(payload),
    });

    // Handle both Incoming Webhook (plain text) and Web API (JSON) responses
    try {
      const contentType = response.headers.get('content-type');
      
      if (contentType?.includes('application/json')) {
        // Future Web API: returns JSON {ok: boolean, error?: string}
        const data = (await response.json()) as SlackApiResponse;
        if (!data.ok) {
          console.error('Slack API Error:', data.error);
          return NextResponse.json(
            { 
              message: 'Error sending message to Slack', 
              error: data.error 
            },
            { status: 500 }
          );
        }
      } else {
        // Current Incoming Webhooks: return plain text "ok"
        if (!response.ok) {
          const errorText = await response.text();
          console.error('Slack webhook failed:', response.status, response.statusText, errorText);
          return NextResponse.json(
            { message: 'Error sending message to Slack' },
            { status: 500 }
          );
        }
      }
    } catch {
      // Fallback if response parsing fails
      if (!response.ok) {
        console.error('Slack request failed:', response.status, response.statusText);
        return NextResponse.json(
          { message: 'Error sending message to Slack' },
          { status: 500 }
        );
      }
    }

    // Persist the message for signed-in senders so it can be shown back to
    // them on /party. Anonymous sends stay stateless, as before.
    if (userId) {
      try {
        await prisma.connectMessage.create({
          data: {
            userId,
            message: sanitizedMessage,
            email: sanitizedEmail,
            firstName: sanitizedFirstName,
            context: sanitizedContext,
          },
        });
      } catch (persistError) {
        console.error('Failed to persist connect message:', persistError);
      }
    }

    return NextResponse.json(
      { message: 'Message sent to Slack successfully' },
      { status: 200 }
    );
  } catch (err) {
    console.error('Error in POST /api/chat/send:', err instanceof Error ? err.message : 'Unknown error');
    return NextResponse.json(
      { 
        message: 'Error sending message',
        error: err instanceof Error ? err.message : 'Unknown error'
      },
      { status: 500 }
    );
  }
}