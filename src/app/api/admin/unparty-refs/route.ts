import { NextResponse } from 'next/server'
import { readFileSync } from 'fs'
import { join } from 'path'
import { auth } from '@/lib/auth-stub.server'
import { adminGuard } from '@/lib/admin'
import { prisma } from '@/lib/prisma'
import type { UnpartyRefsManifest } from '@/lib/unparty-refs'
import { setupStepId } from '../../../../../prisma/setup-steps'

/**
 * The unparty button's data (/admin/unparty): the manifest of every remaining
 * unparty reference, generated at build time by scripts/generate-unparty-refs.js
 * (deployed, there is no source tree to scan), with whether the caller has the
 * SETUP. "brand" step done. Completing it (once the manifest reports none
 * left) is the onboarding's one checker's job now (src/lib/setup-verify.ts,
 * #589), not a side effect of opening this page
 */
// Gitignored and generated by every build and `npm run dev`, so it is read at
// request time rather than imported: a fresh copy type-checks before it exists
const MANIFEST_FILE = join(process.cwd(), 'src', 'data', 'unpartyRefsManifest.json')

function readManifest(): UnpartyRefsManifest | null {
  try {
    return JSON.parse(readFileSync(MANIFEST_FILE, 'utf8')) as UnpartyRefsManifest
  } catch {
    return null
  }
}

export async function GET(request: Request) {
  const denied = await adminGuard()
  if (denied) return denied

  const manifest = readManifest()
  if (!manifest) {
    return NextResponse.json(
      { error: 'Not counted yet: run npm run dev or npm run build to generate src/data/unpartyRefsManifest.json' },
      { status: 404 }
    )
  }
  // ?summary=1: just the number left, for the /admin row (skips the listing and the step check)
  if (new URL(request.url).searchParams.has('summary')) {
    const { measured, done, total } = manifest
    return NextResponse.json({ measured, done, remaining: total.matches + total.paths })
  }

  const stepId = setupStepId('brand')
  const setupStep = { id: stepId, seeded: false, completed: false }

  // Reads the SETUP. step's progress; never blocks the listing when the step
  // is not seeded yet or the database is unreachable
  try {
    const step = await prisma.step.findUnique({ where: { id: stepId }, select: { id: true } })
    if (step) {
      setupStep.seeded = true
      const { userId } = await auth()
      if (userId) {
        const progress = await prisma.userStepProgress.findUnique({
          where: { userId_stepId: { userId, stepId } },
          select: { completed: true },
        })
        setupStep.completed = progress?.completed ?? false
      }
    }
  } catch (error) {
    console.error('unparty-refs: SETUP. step check failed:', error)
  }

  return NextResponse.json({ ...manifest, setupStep })
}
