import videoMetadata from '../../../data/videoMetadata.json';
import type { VideoRegistryEntry } from './types';

// title/description are pulled from each UNPPP's own EditorialArticle
// (the real, hand-written copy already public on that route) rather than
// UnpppsConfig.json's `description` field, which is often just a
// placeholder (e.g. "THEUNPARTYAPI"). Cross-referenced against
// src/data/UnpppsConfig.json for `coverVideo`/`cover` as of this writing —
// re-check both sources before editing an entry.
//
// duration/uploadDate/thumbnailUrl are NOT hand-entered here - they're
// merged in below from src/data/videoMetadata.json, generated by
// `npm run generate-video-metadata` (ffprobe/ffmpeg + git history, #956).
// Keyed by asset path (contentUrl), not slug - videoMetadata.json covers
// every video file under public/, independent of what's registered here,
// and a bare filename/slug key can't disambiguate assets that share a
// filename at different paths (e.g. llm_baseline.mp4 exists twice).
const VIDEO_METADATA = videoMetadata as Record<
  string,
  { duration?: string; uploadDate?: string; thumbnailUrl?: string }
>;

const VIDEO_ENTRIES_BASE: VideoRegistryEntry[] = [];

// Generated fields first, entry second - an entry that hand-sets
// thumbnailUrl (or, hypothetically, duration/uploadDate) always wins over
// videoMetadata.json; a field the entry simply omits falls through to the
// generated value. Object spread only overrides keys actually present in
// the later operand, so this works correctly for keys `entry` never sets.
export const VIDEO_REGISTRY_ENTRIES: VideoRegistryEntry[] = VIDEO_ENTRIES_BASE.map((entry) => ({
  ...VIDEO_METADATA[entry.contentUrl],
  ...entry,
}));
