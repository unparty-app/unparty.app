import { existsSync, readFileSync } from 'fs'
import { join } from 'path'
import { prisma } from '@/lib/prisma'
import { calculatePriorityCount, getUrlPoints } from '@/utils/unppp-priority-count'
import { calculateRepoPriorityCount } from '@/utils/repo-priority-count'
import { getStepLinkPoints } from '@/utils/step-priority-count'
import { buildStoryMentionCounts, getStoryMentionPoints } from '@/utils/story-mention-count'
import { classifyByPercentile, type Classification } from '@/utils/percentile-classification'

/**
 * Shared join of UnpppsConfig.json x raw-repo-metadata.json x Step links x
 * story mentions into a per-unppp priority score. Single source of truth
 * for /api/unppp/priority-score and the UNPPP-scoped BuildStatus generator
 * (src/utils/buildStatusParser.ts) — previously duplicated independently in
 * both places (plus src/app/utils/priorityTableData.ts and
 * scripts/priority-count-debug.ts, left as-is — different constraints:
 * client-fetch without Prisma access, and a CLI with its own flags).
 */

interface UnpppConfigEntry {
  id: string
  name?: string
  repoName?: string
  [key: string]: unknown
}

export interface UnpppPriorityScoreRow {
  id: string
  name: string
  unpppTotal: number
  repoTotal: number
  stepLinkPoints: number
  storyMentionPoints: number
  urlPoints: number
  combined: number
  moodClassification: Classification
  priorityClassification: Classification
  matched: boolean
}

export async function computeUnpppPriorityScores(): Promise<UnpppPriorityScoreRow[]> {
  const repoMetadataPath = join(process.cwd(), 'public/raw-repo-metadata.json')
  const unpppConfigPath = join(process.cwd(), 'src/data/UnpppsConfig.json')
  const storyMappingsPath = join(process.cwd(), 'public/data/story-repo-mappings.json')

  const repoMetadata: Record<string, unknown>[] = JSON.parse(readFileSync(repoMetadataPath, 'utf-8'))
  const unpppConfig: { unppps: UnpppConfigEntry[] } = JSON.parse(readFileSync(unpppConfigPath, 'utf-8'))
  // Generated by `npm run build` (analyze-story-repo-mentions) and gitignored, so a
  // fresh copy running `npm run dev` doesn't have it yet. Score without story mentions.
  const storyMappings: { mappings: Record<string, { mentionedRepositories: string[] }> } = existsSync(storyMappingsPath)
    ? JSON.parse(readFileSync(storyMappingsPath, 'utf-8'))
    : { mappings: {} }

  const linkedSteps = await prisma.step.findMany({
    where: { unpppId: { not: null } },
    select: { unpppId: true },
    distinct: ['unpppId'],
  })
  const linkedUnpppIds = new Set(linkedSteps.map(s => s.unpppId as string))
  const storyMentionCounts = buildStoryMentionCounts(storyMappings.mappings)

  const repoByUnpppId = new Map(
    repoMetadata
      .filter((r): r is typeof r & { unppp_id: string } => typeof r.unppp_id === 'string' && !!r.unppp_id)
      .map(r => [r.unppp_id, r])
  )
  const repoByName = new Map(repoMetadata.map(r => [r.name as string, r]))

  const rows = unpppConfig.unppps.map(entry => {
    const unpppScore = calculatePriorityCount(entry)
    const repoRow = repoByUnpppId.get(entry.id) ?? repoByName.get(entry.repoName || entry.id)
    const repoScore = calculateRepoPriorityCount(repoRow)
    const stepLinkPoints = getStepLinkPoints(entry.id, linkedUnpppIds)
    const storyMentionPoints = getStoryMentionPoints(entry.id, storyMentionCounts)
    const urlPoints = getUrlPoints(entry.url)

    return {
      id: entry.id,
      name: entry.name ?? entry.id,
      unpppTotal: unpppScore.total,
      repoTotal: repoScore.total,
      stepLinkPoints,
      storyMentionPoints,
      urlPoints,
      combined: unpppScore.total + repoScore.total + stepLinkPoints + storyMentionPoints,
      matched: repoRow !== undefined,
    }
  })

  const combinedValues = rows.map(r => r.combined)
  const repoTotalValues = rows.map(r => r.repoTotal)

  return rows.map(row => ({
    ...row,
    moodClassification: classifyByPercentile(combinedValues, row.combined),
    priorityClassification: classifyByPercentile(repoTotalValues, row.repoTotal),
  }))
}
