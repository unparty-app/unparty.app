#!/usr/bin/env node

/**
 * Hand-written phrases for the site's pills, in the same single-stroke script
 * as "build yours" (src/app/components/build-yours/lettering.ts): Hershey
 * Script 1-stroke, a pen-plotter font in the public domain
 * (scripts/data/hershey-script1.json).
 *
 * Each glyph's polylines are laid out along the line, smoothed into curves
 * (Catmull-Rom, as cubic Béziers), and ordered left to right, the way a hand
 * writes them. Each stroke carries its length, so the write-on keeps
 * one pen speed. Same scale and baseline as lettering.ts, so phrases sit
 * beside "build yours" at one size.
 *
 * Usage:
 *   node scripts/generate-lettering.mjs                 # writes PHRASES to phrases.ts
 *   node scripts/generate-lettering.mjs --print "build yours"
 */

import fs from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

// The phrases the site writes by hand (besides "build yours", lettering.ts)
export const PHRASES = ['try it', 'price yours', 'take it', 'start', 'stop', 'releases', 'nah'];

const ROOT = process.cwd();
const FONT = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'data', 'hershey-script1.json'), 'utf8'));
const OUT = path.join(ROOT, 'src', 'app', 'components', 'build-yours', 'phrases.ts');

// lettering.ts's scale and baseline: font units → viewBox units, y flipped
const SCALE = 1 / 26.67;
const BASELINE = 25.114;
const HEIGHT = 40;
const PAD = 0.3;

const round = (n) => Math.round(n * 100) / 100;

// A glyph's path ("M x y L x y x y M …") as polylines in font units
function polylines(d) {
  const lines = [];
  for (const part of d.split('M').map((p) => p.trim()).filter(Boolean)) {
    const nums = part.replace(/L/g, ' ').trim().split(/[\s,]+/).map(Number);
    const points = [];
    for (let i = 0; i + 1 < nums.length; i += 2) points.push([nums[i], nums[i + 1]]);
    if (points.length > 1) lines.push(points);
  }
  return lines;
}

// Catmull-Rom through the points, as one cubic Bézier path
function smooth(points) {
  const p = points;
  let d = `M${round(p[0][0])} ${round(p[0][1])}`;
  for (let i = 0; i < p.length - 1; i++) {
    const p0 = p[i - 1] ?? p[i];
    const p1 = p[i];
    const p2 = p[i + 1];
    const p3 = p[i + 2] ?? p2;
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${round(c1[0])} ${round(c1[1])} ${round(c2[0])} ${round(c2[1])} ${round(p2[0])} ${round(p2[1])}`;
  }
  return d;
}

const length = (points) => points.slice(1).reduce((sum, q, i) => sum + Math.hypot(q[0] - points[i][0], q[1] - points[i][1]), 0);

/** A phrase as strokes in lettering.ts's shape: { viewBox, strokes: [{ d, len }] } */
export function letter(phrase) {
  let pen = 0;
  const lines = [];
  for (const char of phrase) {
    const glyph = FONT.glyphs[char] ?? FONT.glyphs[' '];
    for (const line of polylines(glyph.d)) {
      lines.push(line.map(([x, y]) => [(pen + x) * SCALE, BASELINE - y * SCALE]));
    }
    pen += glyph.adv;
  }

  // One stroke per polyline, as lettering.ts has them: letters meet but each
  // keeps its own strokes, so the pen lifts between them
  const joined = lines.map((line) => [...line]);

  // Left to right, then shifted so the ink starts at the pad
  joined.sort((a, b) => Math.min(...a.map((q) => q[0])) - Math.min(...b.map((q) => q[0])));
  const minX = Math.min(...joined.flat().map((q) => q[0]));
  const maxX = Math.max(...joined.flat().map((q) => q[0]));
  const shifted = joined.map((line) => line.map(([x, y]) => [x - minX + PAD, y]));

  return {
    viewBox: `0 0 ${round(maxX - minX + PAD * 2)} ${HEIGHT}`,
    strokes: shifted.map((line) => ({ d: smooth(line), len: round(length(line)) })),
  };
}

function write() {
  const entries = PHRASES.map((phrase) => `  ${JSON.stringify(phrase)}: ${JSON.stringify(letter(phrase))},`).join('\n');
  const file = `// Hand-written phrases for the site's pills, in "build yours"'s hand:
// Hershey Script 1-stroke (public domain), same scale and baseline as
// lettering.ts. Generated by scripts/generate-lettering.mjs; regenerate
// rather than hand-edit (add a phrase to PHRASES there).

export interface Lettering {
  viewBox: string;
  strokes: { d: string; len: number }[];
}

export const PHRASES: Record<string, Lettering> = {
${entries}
};
`;
  fs.writeFileSync(OUT, file);
  console.log(`✍️  lettering: ${PHRASES.join(', ')} → ${path.relative(ROOT, OUT)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const at = process.argv.indexOf('--print');
  if (at > -1) console.log(JSON.stringify(letter(process.argv[at + 1] ?? 'build yours')));
  else write();
}
